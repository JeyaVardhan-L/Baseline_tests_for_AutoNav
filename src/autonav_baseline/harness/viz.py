"""
Visual artifacts for one run, generated by the pipeline (never by hand): artifacts/runs/<id>/viz/

  manifest.json      provenance for every layer (dataset, frames, stages, parameters, run id, commit, evidence)
  clouds/*.bin       decimated clouds, uint16 xyz interleaved, dequantise with origin + scale from the manifest
  trajectory.json    estimated (aligned) and ground-truth trajectories with per-pose error
  series.json        per-frame latency per stage, iterations, inlier ratio, residual, accepted

Excerpts are deliberately few and heavily decimated. Source data licences require attribution
(CC BY-NC-SA 4.0 for Newer College and Oxford Spires); the manifest carries it.
"""

import csv
import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np

from autonav_baseline.datasets.registry import get_adapter
from autonav_baseline.harness.config import resolve_dataset
from autonav_baseline.lidar.filtering import filter_by_range, remove_invalid_points, statistical_outlier_removal, voxel_downsample
from autonav_baseline.lidar.odometry import RegistrationGate, icp_point_to_point

MAX_POINTS = {"raw": 8000, "range": 6000, "voxel": 6000, "outlier": 6000, "source_before": 5000,
              "source_after": 5000, "target": 5000}


def _decimate(pts: np.ndarray, max_n: int) -> np.ndarray:
    if len(pts) <= max_n:
        return pts
    stride = int(np.ceil(len(pts) / max_n))
    return pts[::stride]


def _write_cloud(path: Path, pts: np.ndarray) -> Dict[str, Any]:
    pts = np.asarray(pts, dtype=np.float64)
    origin = pts.min(axis=0)
    extent = float((pts.max(axis=0) - origin).max()) or 1.0
    scale = extent / 65535.0
    q = np.round((pts - origin) / scale).astype(np.uint16)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(q.astype("<u2").tobytes())
    return {"n_points": int(len(pts)), "origin": origin.tolist(), "scale": scale, "dtype": "uint16-le",
            "layout": "xyz interleaved", "max_quantisation_error_m": scale / 2}


def _frames_at(adapter, indices: List[int]):
    want = set(indices)
    got = {}
    for k, fr in enumerate(adapter.get_lidar_frames(max_frames=max(indices) + 1)):
        if k in want:
            got[k] = fr
    return got


def _stages(raw: np.ndarray, params: Dict[str, Any], with_outlier: bool = False):
    valid, _ = remove_invalid_points(raw)
    rng, _ = filter_by_range(valid, params["min_range"], params["max_range"])
    vox, _ = voxel_downsample(rng, params["voxel_size"]) if params["voxel_size"] > 0 else (rng, None)
    out = {"raw": valid, "range": rng, "voxel": vox}
    if with_outlier:
        out["outlier"] = statistical_outlier_removal(vox, 16, 2.0)[0]
    return out


def _read_rows(path: Path) -> List[Dict[str, str]]:
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def export_viz(run_dir: Path, run: Dict[str, Any], summary: Dict[str, Any]) -> Dict[str, Any]:
    viz = run_dir / "viz"
    (viz / "clouds").mkdir(parents=True, exist_ok=True)
    ds = resolve_dataset(run["dataset"]["id"])
    params = run["parameters"]
    start = run["window"]["start"]
    rows = _read_rows(run_dir / "repeats" / "rep0" / "frames.csv")
    mode = run["mode"]
    evidence = {"REAL": "REAL", "REAL-NON-CONSECUTIVE": "NON-CONSECUTIVE", "SYNTHETIC": "SYNTHETIC"}.get(ds["evidence"], ds["evidence"])
    adapter = get_adapter(ds["adapter"], root_path=Path(ds["frames"]) if ds["frames"] else None)
    prov = {"dataset": ds["id"], "sequence": ds["sequence"], "sensor": ds["sensor"], "licence": ds["licence"],
            "evidence": evidence, "run_id": run["run_id"], "commit": run["git"]["commit"], "variant": run["variant"],
            "parameters": params, "hardware_label": run["hardware_label"],
            "attribution": "Data: " + ds["sequence"] + " (" + ds["licence"] + "); decimated excerpts for illustration only."}
    layers: List[Dict[str, Any]] = []
    pairs: Dict[str, Any] = {}

    def add(name, role, stage, frame_idx, pts, space, note=""):
        info = _write_cloud(viz / "clouds" / f"{name}.bin", _decimate(pts, MAX_POINTS.get(stage, 5000)))
        layers.append({"id": name, "role": role, "stage": stage, "frame_index": frame_idx, "space": space,
                       "points_before_decimation": int(len(pts)), "file": f"clouds/{name}.bin", "note": note, **info})

    ok_rows = [r for r in rows if r["warmup"] == "0" and r["total_ms"] != ""]
    if mode == "single-frame":
        med = float(np.median([float(r["total_ms"]) for r in ok_rows]))
        pick = min(ok_rows, key=lambda r: abs(float(r["total_ms"]) - med))
        k = int(pick["frame_index"])
        fr = _frames_at(adapter, [k])[k]
        st = _stages(fr.points, params, with_outlier=True)
        for stage, pts in st.items():
            add(f"stage_{stage}", "stage", stage, k, pts, "sensor frame")
        pairs["stage_frame"] = {"frame_index": k, "stages": {s: int(len(p)) for s, p in st.items()}}
    else:
        reg = [r for r in ok_rows if int(r["frame_index"]) > start and r["accepted"] != ""]
        acc = [r for r in reg if r["accepted"] == "1"] or reg
        med = float(np.median([float(r["total_ms"]) for r in acc]))
        typical = min(acc, key=lambda r: abs(float(r["total_ms"]) - med))
        worst = max(reg, key=lambda r: float(r["total_ms"]))
        gate = RegistrationGate()
        for label, row in (("typical", typical), ("worst", worst)):
            k = int(row["frame_index"])
            frs = _frames_at(adapter, [k - 1, k])
            tgt = _stages(frs[k - 1].points, params)["voxel"]
            src_stages = _stages(frs[k].points, params)
            src = src_stages["voxel"]
            res = icp_point_to_point(src, tgt, params["max_correspondence_distance"], params["max_iterations"], params["tolerance"])
            after = src @ res.rotation.T + res.translation
            add(f"{label}_target", "target", "target", k - 1, tgt, f"sensor frame of scan {k - 1}")
            add(f"{label}_source_before", "source_before", "source_before", k, src, f"sensor frame of scan {k}")
            add(f"{label}_source_after", "source_after", "source_after", k, after, f"scan {k} registered into scan {k - 1}")
            if label == "typical":
                for stage in ("raw", "range", "voxel"):
                    add(f"stage_{stage}", "stage", stage, k, src_stages[stage], "sensor frame")
            ok, reason = gate.check(res)
            pairs[label] = {"frame_index": k, "total_ms": float(row["total_ms"]), "icp_iterations": res.iterations,
                            "inlier_ratio": res.inlier_ratio, "residual_m": res.fitness_score, "accepted": ok,
                            "reject_reason": "" if ok else reason, "residual_history_m": res.residual_history,
                            "transform_target_from_source": res.transformation.tolist()}

    manifest = {"provenance": prov, "layers": layers, "pairs": pairs,
                "window": run["window"], "colour_roles": ["source_before", "source_after", "target", "stage"]}
    (viz / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    npz = run_dir / "accuracy_per_pose.npz"
    if npz.is_file():
        z = np.load(npz)
        t = z["t"]
        traj = {"provenance": prov, "t_s": (t - t[0]).round(3).tolist(),
                "gt_xyz": z["gt_xyz"].round(3).tolist(), "est_aligned_xyz": z["est_aligned_xyz"].round(3).tolist(),
                "ate_m": z["ate_m"].round(4).tolist(),
                "alignment": "rigid SE(3) Umeyama of the estimate onto ground truth (positions, no scale)"}
        (viz / "trajectory.json").write_text(json.dumps(traj), encoding="utf-8")

    cols = ["frame_index", "load_ms", "preprocess_ms", "register_ms", "total_ms", "e2e_ms", "icp_iterations",
            "inlier_ratio", "residual_m", "accepted", "points_voxel", "warmup"]
    series = {"provenance": prov, "columns": cols,
              "rows": [[(float(r[c]) if r[c] not in ("", None) else None) for c in cols] for r in rows]}
    (viz / "series.json").write_text(json.dumps(series), encoding="utf-8")
    return {"layers": len(layers)}